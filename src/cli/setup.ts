import { access, copyFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { stdin as input, stdout as output } from 'node:process'
import { createInterface } from 'node:readline/promises'
import { siteConfigSchema } from '../core/config.ts'
import { parseArgs } from './args.ts'

interface Answers {
  name: string
  email: string
  homepage: string
  github: string
  titleZh: string
  descriptionZh: string
  taglineZh: string
  titleEn: string
  descriptionEn: string
  taglineEn: string
  url: string
  domain: string
  theme: string
  repoOwner: string
  repoName: string
}

const DEFAULTS: Answers = {
  name: 'Your Name',
  email: '',
  homepage: '',
  github: '',
  titleZh: '你的博客',
  descriptionZh: '用一句话说明这个博客写什么。',
  taglineZh: '一句更短的副标题。',
  titleEn: 'Your Blog',
  descriptionEn: 'One sentence about what this blog covers.',
  taglineEn: 'A shorter subtitle.',
  url: 'http://localhost:4000',
  domain: '',
  theme: 'folio',
  repoOwner: '',
  repoName: '',
}

function value(args: ReturnType<typeof parseArgs>, name: string, fallback: string): string {
  return args.options.get(name) ?? fallback
}

async function exists(file: string): Promise<boolean> {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

function buildConfig(answers: Answers): string {
  const github = answers.github
    ? `[{ label: 'GitHub', url: ${JSON.stringify(answers.github)} }]`
    : '[]'
  const repository =
    answers.repoOwner && answers.repoName
      ? `\n    repository: { owner: ${JSON.stringify(answers.repoOwner)}, name: ${JSON.stringify(answers.repoName)} },`
      : ''
  const customDomain = answers.domain
    ? `\n    customDomain: ${JSON.stringify(answers.domain)},`
    : ''

  return `// Generated by dxbe setup. Edit freely.
import { defineConfig } from 'dxbe/config'

export default defineConfig({
  identity: {
    author: {
      name: ${JSON.stringify(answers.name)},
      email: ${JSON.stringify(answers.email)},
      url: ${JSON.stringify(answers.homepage)},
      avatar: '',
    },
    social: ${github},${repository}
  },
  locales: {
    default: 'zh',
    entries: {
      zh: {
        label: '中文',
        title: ${JSON.stringify(answers.titleZh)},
        description: ${JSON.stringify(answers.descriptionZh)},
        tagline: ${JSON.stringify(answers.taglineZh)},
      },
      en: {
        label: 'English',
        title: ${JSON.stringify(answers.titleEn)},
        description: ${JSON.stringify(answers.descriptionEn)},
        tagline: ${JSON.stringify(answers.taglineEn)},
      },
    },
  },
  site: {
    url: ${JSON.stringify(answers.url)},
    base: '/',${customDomain}
    timezone: 'Asia/Shanghai',
    license: {
      code: 'MIT',
      content: 'CC BY-NC-SA 4.0',
    },
  },
  theme: {
    name: ${JSON.stringify(answers.theme)},
    config: {},
  },
  nav: [
    { key: 'home', path: '/' },
    { key: 'archives', path: '/archives/' },
    { key: 'tags', path: '/tags/' },
    { key: 'about', path: '/about/' },
  ],
  pagination: {
    perPage: 10,
  },
  features: {
    search: true,
    math: true,
    autoLanguage: true,
  },
})
`
}

export async function runSetup(argv: string[] = process.argv.slice(2)): Promise<void> {
  const args = parseArgs(argv)
  const configFile = path.join(process.cwd(), 'site.config.ts')
  const configExists = await exists(configFile)
  const yes = args.flags.has('--yes')
  const force = args.flags.has('--force')

  if (configExists && yes && !force) {
    throw new Error('site.config.ts already exists; pass --force to overwrite')
  }

  const answers: Answers = {
    name: value(args, '--name', DEFAULTS.name),
    email: value(args, '--email', DEFAULTS.email),
    homepage: value(args, '--homepage', DEFAULTS.homepage),
    github: value(args, '--github', DEFAULTS.github),
    titleZh: value(args, '--title-zh', DEFAULTS.titleZh),
    descriptionZh: value(args, '--description-zh', DEFAULTS.descriptionZh),
    taglineZh: value(args, '--tagline-zh', DEFAULTS.taglineZh),
    titleEn: value(args, '--title-en', DEFAULTS.titleEn),
    descriptionEn: value(args, '--description-en', DEFAULTS.descriptionEn),
    taglineEn: value(args, '--tagline-en', DEFAULTS.taglineEn),
    url: value(args, '--url', DEFAULTS.url),
    domain: value(args, '--domain', DEFAULTS.domain),
    theme: value(args, '--theme', DEFAULTS.theme),
    repoOwner: value(args, '--repo-owner', DEFAULTS.repoOwner),
    repoName: value(args, '--repo-name', DEFAULTS.repoName),
  }

  if (!yes) {
    const rl = createInterface({ input, output })
    const ask = async (label: string, current: string): Promise<string> => {
      const answer = await rl.question(`${label}${current ? ` [${current}]` : ''}: `)
      return answer.trim() || current
    }
    try {
      if (configExists) {
        const overwrite = (await ask('site.config.ts exists. Overwrite? (y/N)', 'N')).toLowerCase()
        if (overwrite !== 'y' && overwrite !== 'yes') {
          console.log('No changes written.')
          return
        }
      }
      answers.name = await ask('Author name', answers.name)
      answers.email = await ask('Author email', answers.email)
      answers.homepage = await ask('Author homepage', answers.homepage)
      answers.github = await ask('GitHub URL', answers.github)
      answers.titleZh = await ask('Chinese site title', answers.titleZh)
      answers.descriptionZh = await ask('Chinese description', answers.descriptionZh)
      answers.taglineZh = await ask('Chinese tagline', answers.taglineZh)
      answers.titleEn = await ask('English site title', answers.titleEn)
      answers.descriptionEn = await ask('English description', answers.descriptionEn)
      answers.taglineEn = await ask('English tagline', answers.taglineEn)
      answers.url = await ask('Site URL (origin only)', answers.url)
      answers.domain = await ask('Custom domain (optional)', answers.domain)
      answers.theme = await ask('Theme (folio/orbital/scholar/apogee/capstan)', answers.theme)
      answers.repoOwner = await ask('GitHub owner (optional)', answers.repoOwner)
      answers.repoName = await ask('GitHub repository (optional)', answers.repoName)
    } finally {
      rl.close()
    }
  }

  if (!['folio', 'orbital', 'scholar', 'apogee', 'capstan'].includes(answers.theme)) {
    throw new Error(
      `Unknown theme "${answers.theme}"; choose folio, orbital, scholar, apogee, or capstan`,
    )
  }
  try {
    new URL(answers.url)
  } catch {
    throw new Error(`site.url must be an absolute URL, got "${answers.url}"`)
  }
  if (answers.domain) {
    answers.domain = answers.domain.replace(/^https?:\/\//, '').replace(/\/.*$/, '')
  }

  const source = buildConfig(answers)
  const validationSource = source
    .replace("import { defineConfig } from 'dxbe/config'", '')
    .replace('export default defineConfig(', 'return (')
  let parsed: unknown
  try {
    const fn = new Function(`${validationSource}`) as () => unknown
    parsed = fn()
  } catch (error) {
    throw new Error(`Generated configuration could not be parsed: ${(error as Error).message}`)
  }

  const checked = siteConfigSchema.safeParse(parsed)
  if (!checked.success) {
    const details = checked.error.issues
      .map((issue) => `${issue.path.join('.') || '(root)'}: ${issue.message}`)
      .join('\n')
    throw new Error(`Generated configuration is invalid:\n${details}`)
  }

  if (configExists) {
    await copyFile(configFile, `${configFile}.bak`)
  }
  await writeFile(configFile, source, 'utf8')
  console.log(
    `wrote ${configExists ? 'site.config.ts (backup: site.config.ts.bak)' : 'site.config.ts'}`,
  )
  console.log('next: npm run dev')
}
